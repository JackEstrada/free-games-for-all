"""Turn thumbs/*.png into 480x300 .webp covers and write assets/meta.js (file sizes + a tint color per game).

Usage (from the site folder):  python tools/build_meta.py
Needs Pillow (pip install pillow).
"""
import json
import os
import re

from PIL import Image

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
catalog = open(os.path.join(ROOT, "assets", "catalog.js"), encoding="utf-8").read()
games = re.findall(r'\{ id: "([a-z0-9-]+)", title: "[^"]*", type: "(html|flash)"', catalog)


def game_size(gid, kind):
    """Bytes on disk: one .swf, one .html, or a whole games/<id>/ folder."""
    if kind == "flash":
        f = os.path.join(ROOT, "flash", gid + ".swf")
        return os.path.getsize(f) if os.path.exists(f) else 0
    folder = os.path.join(ROOT, "games", gid)
    if os.path.isdir(folder):
        return sum(os.path.getsize(os.path.join(r, f)) for r, _, fs in os.walk(folder) for f in fs)
    f = os.path.join(ROOT, "games", gid + ".html")
    return os.path.getsize(f) if os.path.exists(f) else 0


meta = {}
for gid, kind in games:
    entry = {"size": game_size(gid, kind)}
    png = os.path.join(ROOT, "thumbs", gid + ".png")
    webp = os.path.join(ROOT, "thumbs", gid + ".webp")
    if os.path.exists(png):
        im = Image.open(png).convert("RGB")
        # cover-crop to 16:10, then shrink
        w, h = im.size
        tw, th = (w, round(w * 10 / 16)) if w / h < 16 / 10 else (round(h * 16 / 10), h)
        left, top = (w - tw) // 2, (h - th) // 2
        im = im.crop((left, top, left + tw, top + th)).resize((480, 300), Image.LANCZOS)
        im.save(webp, "WEBP", quality=80, method=6)
        os.remove(png)
    if os.path.exists(webp):
        r, g, b = Image.open(webp).convert("RGB").resize((1, 1), Image.BOX).getpixel((0, 0))
        k = 0.55  # darken so white title text on the placeholder stays readable
        entry["tint"] = "#%02x%02x%02x" % (int(r * k), int(g * k), int(b * k))
    meta[gid] = entry

missing = [g for g, _ in games if "tint" not in meta[g]]
with open(os.path.join(ROOT, "assets", "meta.js"), "w", encoding="utf-8") as out:
    out.write("/* Generated by tools/build_meta.py. File sizes and cover tints. */\n")
    out.write("window.META = " + json.dumps(meta, separators=(",", ":")) + ";\n")
print(f"{len(meta)} games, {len(missing)} without a cover: {missing}")
